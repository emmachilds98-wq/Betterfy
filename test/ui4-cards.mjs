import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';

export const BUNDLE = readFileSync(new URL('../docs/index.html', import.meta.url), 'utf8');
export const GOLDEN = new URL('./fixtures/ui4/', import.meta.url);

const between = (from, to, what) => {
  const i = BUNDLE.indexOf(from), j = BUNDLE.indexOf(to, i);
  assert.ok(i > 0 && j > i, `${what} not found — rebuild with node build-web.mjs`);
  return BUNDLE.slice(i, j);
};
const line = re => {
  const m = BUNDLE.match(re);
  assert.ok(m, `could not lift ${re} out of the bundle`);
  return m[0];
};

