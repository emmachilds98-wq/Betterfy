/** A sandbox with the card views in it. `renderers` stands in for web/ui/sound.mjs. */
export function cards({ S = {}, R = {}, renderers = {} } = {}) {
  const sandbox = {
    R: { backlog: [], ...R },
    S: { inboxAt: 0, fileSel: new Set(), fileSelFor: null, discAt: 0, discoverFrom: 'Jungle & Breaks', ...S },
    FB: {}, CFG,
    LIB: { playlists: [
      { id: 'p1', name: 'Jungle & Breaks', tracks: Array(40).fill({ id: 'x' }) },
      { id: 'p2', name: 'Late Night <Deep>', tracks: Array(20).fill({ id: 'y' }) },
    ] },
    LS: { getItem: k => (k === 'bf_lfm' ? 'lfm-key' : null) },
    matchMedia: () => ({ matches: false }),
    hueOf: () => 200,
    ICON_PLAY: '<svg id="playicon"></svg>',
    toast() {}, render() {}, console,
    ...renderers,
  };
  vm.createContext(sandbox);
  vm.runInContext(line(/const esc = [^\n]+/), sandbox);
  vm.runInContext(line(/const mmss = [^\n]+/), sandbox);
  vm.runInContext(between('/* Generated by bundler.mjs', '/* =============================================================== */', 'the scoring core'), sandbox);
  vm.runInContext(between('/** A row of tag chips', 'function describe(rows)', 'tagChips'), sandbox);
  vm.runInContext(between('function artHTML(t', 'function cmpTable(o)', 'vInbox'), sandbox);
  vm.runInContext(between('/** The discovery currently on the card. */', 'function vHistory()', 'vDiscover'), sandbox);
  return sandbox;
}

