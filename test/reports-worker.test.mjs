// buildReports runs in docs/reports-worker.js when the page has workers
// (docs/archive/BUILD-6-PLAN.md D4). The worker is the page's own reports.js, so the
// answer must be the page's answer: same function, same output, from a request
// that carries the page state (rejections, pinned mirror, listening, verdicts).
import test from 'node:test';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFileSync } from 'node:fs';

const BUNDLE = readFileSync(new URL('../docs/index.html', import.meta.url), 'utf8');
const WORKER = readFileSync(new URL('../docs/reports-worker.js', import.meta.url), 'utf8');

const tr = (id, artist, added, extra = {}) => ({ id, name: 'Song ' + id, artists: [{ id: 'a-' + artist, name: artist }], album: 'Alb ' + id,
  albumType: 'album', released: '2020', duration_ms: 200000 + id.length, isrc: 'ISRC' + id, added_at: added, ...extra });
const tags = {};
for (const [a, g] of [['h1', 'house'], ['h2', 'house'], ['h3', 'deep house'], ['t1', 'techno'], ['t2', 'techno'], ['t3', 'minimal techno'], ['u1', 'house'], ['u2', 'techno']])
  tags['a-' + a] = { tags: [[g, 100], ['electronic', 60], [g === 'house' ? 'dance' : 'dark', 40], ['club', 30], ['dj', 20]] };
const mk = (artist, n, p) => Array.from({ length: n }, (_, i) => tr(`${p}${artist}${i}`, artist, `2024-0${1 + (i % 9)}-01`));
const house = [...mk('h1', 8, 'x'), ...mk('h2', 8, 'x'), ...mk('h3', 8, 'x')];
const techno = [...mk('t1', 8, 'x'), ...mk('t2', 8, 'x'), ...mk('t3', 8, 'x')];
const dupe = tr('dupe-b', 'h1', '2024-02-02', { name: house[0].name, isrc: house[0].isrc });
const lib = {
  user: { id: 'u' },
  playlists: [
    { id: 'p-house', name: 'House', tracks: [...house, dupe, techno[0]] },       // a repeat, and a cross-filed track
    { id: 'p-techno', name: 'Techno', tracks: techno },
    { id: 'p-all', name: 'All Songs — Betterfy', tracks: [...house, ...techno] },  // the mirror, ignored
  ],
  liked: [tr('l1', 'u1', '2025-01-01'), tr('l2', 'u2', '2025-02-01'), tr('l3', 'h1', '2025-03-01'), tr('l4', 'nobody', '2025-04-01'),
          tr('l5', 'u1', '2025-05-01'), tr('l6', 'u2', '2025-06-01'), house[3], techno[4]],
};
const cfg = { 'p-house': { name: 'House', axis: 'genre', target: true }, 'p-techno': { name: 'Techno', axis: 'genre', target: true },
              'p-all': { name: 'All Songs — Betterfy', axis: 'context', target: false } };
const FB = { l1: { rejected: ['p-house'], skips: 1 }, l5: { skips: 2 } };
const listening = { weights: new Map([['a-u2', 5]]), tracks: null };
const shadow = { rows: [{ id: 'l1', decision: { kind: 'confident' } }, { id: 'l2', decision: { kind: 'unsure' } }] };

/** Maps and Sets as arrays, and out of the vm's realm, so two answers compare by value. */
const plain = v => {
  const tag = Object.prototype.toString.call(v);   // instanceof does not cross the vm's realm
  if (tag === '[object Map]') return { __map: Array.from(v, ([k, x]) => [plain(k), plain(x)]) };
  if (tag === '[object Set]') return { __set: Array.from(v, plain) };
  if (Array.isArray(v)) return Array.from(v, plain);
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, plain(x)]));
  return v;
};
const cut = (a, b) => { const i = BUNDLE.indexOf(a), j = BUNDLE.indexOf(b, i); assert.ok(i > 0 && j > i, a + ' — rebuild with npm run build:web'); return BUNDLE.slice(i, j); };

/** The page's own buildReports, on the main thread. */
function onPage() {
  const sb = { console, FB: structuredClone(FB), LS: { getItem: () => null, setItem() {} }, LC: listening, ENG: { shadow } };
  vm.createContext(sb);
  vm.runInContext(cut('/* Generated by bundler.mjs', '/* ---------- storage ----------'), sb);
  vm.runInContext('const mmss = ms => ms == null ? "—" : `${Math.floor(ms/60000)}:${String(Math.round(ms%60000/1000)).padStart(2,"0")}`;'
    + ' const ALL_SONGS_NAME = "All Songs — Betterfy"; var LISTENING_CACHE = LC;', sb);
  vm.runInContext(cut('/* ---------- reports (mirrors', '/* ===================== UI'), sb);
  return plain(sb.buildReports(structuredClone(lib), cfg, structuredClone(tags)));
}

/** The same request the page posts, answered by the worker's own script. */
function inWorker(extra = {}) {
  const posted = [];
  const sb = { console, performance, self: { postMessage: m => posted.push(m) } };
  vm.createContext(sb);
  vm.runInContext(WORKER, sb);
  sb.self.onmessage({ data: { id: 7, lib: structuredClone(lib), cfg, tags: structuredClone(tags), fb: structuredClone(FB), pinned: null,
    allSongsName: 'All Songs — Betterfy', listening, shadow, ...extra } });
  assert.equal(posted.length, 1);
  return posted[0];
}

test('the worker builds the same reports as the page, from the same request', () => {
  const msg = inWorker();
  assert.equal(msg.ok, true, msg.error);
  assert.equal(msg.id, 7);
  const here = onPage();
  const there = plain(msg.result);
  assert.ok(here.backlog.length >= 4 && here.within.length && here.across.length, 'the fixture must exercise the report');
  assert.deepEqual(there, here);
});

test('the worker honours the pinned mirror playlist, whatever it is named now', () => {
  const renamed = structuredClone(lib);
  renamed.playlists[2].name = 'My everything list';
  const msg = inWorker({ lib: renamed, pinned: 'p-all', cfg: { ...cfg, 'p-all': { ...cfg['p-all'], name: 'My everything list' } } });
  assert.equal(msg.ok, true, msg.error);
  assert.deepEqual(plain(msg.result).backlog.map(b => b.id), onPage().backlog.map(b => b.id));
});

test('a request the worker cannot answer comes back as an error, not silence', () => {
  const msg = inWorker({ lib: null });
  assert.equal(msg.ok, false);
  assert.equal(msg.id, 7);
  assert.ok(msg.error);
});

test('the page falls back to the main thread when there is no Worker', async () => {
  const sb = { console, FB: {}, LS: { getItem: () => null, setItem() {} } };
  vm.createContext(sb);
  vm.runInContext(cut('/* Generated by bundler.mjs', '/* ---------- storage ----------'), sb);
  vm.runInContext('const mmss = () => "0:00"; const ALL_SONGS_NAME = "All Songs";', sb);
  vm.runInContext(cut('/* ---------- reports (mirrors', '/* ===================== UI'), sb);
  const R = await vm.runInContext(`buildReportsAsync(${JSON.stringify(lib)}, ${JSON.stringify(cfg)}, ${JSON.stringify(tags)})`, sb);
  assert.ok(R.backlog.length >= 4);
});

test('artistHistory reads the same answer from the shared index as from a scan', async () => {
  const { artistHistory, artistHistoryIndex } = await import('../profile.mjs');
  const targets = new Set(['p-house', 'p-techno']);
  const index = artistHistoryIndex(lib, targets);
  const probes = [...lib.liked, ...house, ...techno, dupe, tr('ghost', 'h1', '2020-01-01'), { id: 'bare', artists: [] }];
  for (const t of probes) assert.deepEqual(artistHistory(t, lib, targets, index), artistHistory(t, lib, targets), t.id);
});
