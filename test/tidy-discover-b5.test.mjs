test('Discover memory: pass and like are remembered, kept apart, and likes boost seeds', () => {
  const store = {};
  const sb = { LS: { getItem: k => store[k] ?? null, setItem: (k, v) => { store[k] = v; } }, norm: s => s.toLowerCase() };
  vm.createContext(sb);
  vm.runInContext(slice('const DISC_MEM_KEY', 'async function runDiscovery', 'discover memory'), sb);
  vm.runInContext("discRemember('like', 'Foo'); discRemember('pass', 'Bar'); discRemember('pass', 'Foo')", sb);
  assert.deepEqual(own(vm.runInContext('discMemory()', sb)), { pass: ['bar', 'foo'], like: [] });
  vm.runInContext("discRemember('like', 'Foo')", sb);
  assert.deepEqual(own(vm.runInContext('discMemory()', sb)), { pass: ['bar'], like: ['foo'] });
  const w = vm.runInContext("discBoostLiked(new Map([['Foo', 1], ['Baz', 4]]), ['foo'])", sb);
  assert.equal(w.get('Foo'), 3); assert.equal(w.get('Baz'), 4);
});

