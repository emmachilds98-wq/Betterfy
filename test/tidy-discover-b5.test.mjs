const own = x => JSON.parse(JSON.stringify(x));
const track = (id, artist, title, over = {}) => ({ id, name: title, artists: [{ id: 'a-' + artist, name: artist }],
  album: 'A' + id, duration_ms: 200000, isrc: 'ISRC' + id, added_at: '2024-01-01T00:00:00Z', ...over });
const TAGS = { 'a-X': { tags: [['jungle', 100]] }, 'a-Y': { tags: [['techno', 100]] }, 'a-Z': { tags: [['jungle', 90], ['techno', 20]] } };

test('withoutTrack takes a member back out of its centroid', () => {
  const home = { n: 2, vec: new Map([['a', 0.5], ['b', 0.5]]) };
  const out = withoutTrack(home, new Map([['a', 1]]));
  assert.deepEqual([...out], [['b', 1]]);
  assert.equal(withoutTrack({ n: 1, vec: home.vec }, new Map([['a', 1]])), home.vec, 'a one-track home is left alone');
  assert.equal(cosine(new Map([['a', 1]]), out), 0);
});

test('Repeats: two spellings of one recording group by ISRC; same name, different ISRC still clash', () => {
  const lib = { user: { id: 'u' }, liked: [], playlists: [
    { id: 'p1', name: 'One', tracks: [track('1', 'X', 'Song', { isrc: 'SAME' }), track('2', 'X', 'Song (Original Mix)', { isrc: 'SAME' }),
      track('3', 'Y', 'Other', { isrc: 'I3' }), track('4', 'Y', 'Other', { isrc: 'I4' })] }] };
  const cfg = { p1: { name: 'One', axis: 'genre', target: true } };
  const r = page().buildReports(lib, cfg, TAGS);
  const v = own(r.within).map(x => [x.verdict, x.options.map(o => o.id).sort().join()]).sort();
  assert.deepEqual(v, [['different-recording', '3,4'], ['same-recording', '1,2']]);
});

test('Cross-filed ranks two genre playlists above genre plus mood, and suggests a keeper', () => {
  const t = track('9', 'X', 'Tune'), u = track('8', 'Y', 'Deep');
  const lib = { user: { id: 'u' }, liked: [], playlists: [
    { id: 'g1', name: 'Jungle', tracks: [t, track('a', 'X', 'a2'), track('b', 'Z', 'b2')] },
    { id: 'g2', name: 'Techno', tracks: [t, track('c', 'Y', 'c2'), track('d', 'Y', 'd2')] },
    { id: 'm1', name: 'Chill', tracks: [u, track('e', 'Y', 'e2')] },
    { id: 'g3', name: 'Techno 2', tracks: [track('f', 'Y', 'f2'), track('g', 'Y', 'g2')] }] };
  const cfg = { g1: { name: 'Jungle', axis: 'genre', target: true }, g2: { name: 'Techno', axis: 'genre', target: true },
    g3: { name: 'Techno 2', axis: 'genre', target: true }, m1: { name: 'Chill', axis: 'mood', target: false } };
  lib.playlists[3].tracks.push(u);
  const r = page().buildReports(lib, cfg, TAGS);
  assert.deepEqual(own(r.across).map(x => x.id), ['9', '8']);
  assert.deepEqual(own(r.across).map(x => x.suspicion), [3, 1]);
  assert.equal(r.across[0].keeper, 'g1', 'a jungle artist fits the jungle playlist');
});

const SOUND = [{ id: 't1', from: 'p1', to: 'p9', band: 'sure' }];
const mf = (id, to) => ({ id, currentPlaylistId: 'p1', suggest: [{ id: to, name: to }] });
test('Tidy: where sound and tags disagree about a track, the tag row is dropped', () => {
  const c = { R: { misfiled: [mf('t1', 'p2'), mf('t2', 'p2'), mf('t3', 'p9')] }, tidySoundRows: () => SOUND };
  assert.deepEqual(TIDY.tagMisfiles(c).map(m => m.id), ['t2', 't3']);
  c.tidySoundRows = () => [{ id: 't2', from: 'p1', to: 'p2' }];
  assert.equal(TIDY.tagMisfiles(c).length, 3, 'agreement keeps the row');
  assert.equal(TIDY.tagMisfiles({ R: c.R }).length, 3, 'no sound tier, no change');
});

