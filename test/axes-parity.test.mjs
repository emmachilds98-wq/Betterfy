test('the page and axes.mjs classify every name identically', () => {
  const lib = { playlists: NAMES.map((n, k) => pl('p' + k, n)) };
  const page = pageClassify()(lib), node = nodeClassify(lib);
  for (const p of lib.playlists) assert.deepEqual(node[p.id], page[p.id], p.name);
  assert.equal(Object.keys(node).length, NAMES.length);
});

test('…and identically on size, dates and tags', () => {
  const tags = {};
  const tagged = (id, name, n, vocab) => {
    const tracks = [];
    for (let k = 0; k < n; k++) {
      const a = `${id}-a${k}`;
      tags[a] = { tags: vocab.map(t => [t, 100]) };
      tracks.push({ id: `${id}-t${k}`, artists: [{ id: a, name: a }],
                    added_at: new Date(NOW - 3 * day - k * 30 * day).toISOString() });
    }
    return { id, name, tracks };
  };
  const lib = { playlists: [
    pl('tiny', 'Tech House', { n: 5 }),                        // below MIN_FOR_TARGET
    pl('night', 'with Sam and Jo', { n: 30, span: 0.3, since: 100 }), // one sitting, long ago
    pl('fresh', 'new one', { n: 30, span: 0.3, since: 3 }),    // one sitting, last week
    pl('quick', 'Jungle', { n: 30, span: 0.3, since: 100 }),   // a genre, however quickly built
    pl('few', 'something', { n: 4, span: 0.1, since: 200 }),   // too few dates to say
    tagged('m', 'saudade', 12, ['chill', 'mellow', 'dreamy', 'downtempo']),
    tagged('e', 'the good ones', 12, ['90s', '80s', 'oldies', 'pop']),
    tagged('gm', 'House', 12, ['chill', 'mellow', 'dreamy', 'downtempo']),
    tagged('g1', 'first thing', 14, ['techno', 'industrial techno', 'hard techno']),
    tagged('g2', 'second thing', 14, ['jungle', 'breakbeat', 'hardcore']),
  ] };
  for (const t of [null, tags]) {
    const page = pageClassify()(lib, t), node = nodeClassify(lib, t);
    for (const p of lib.playlists) assert.deepEqual(node[p.id], page[p.id], `${p.name} (tags: ${!!t})`);
  }
  // And these really do exercise each rule, rather than all falling through.
  const of = nodeClassify(lib, tags);
  assert.equal(of.tiny.target, false);
  assert.equal(of.night.axis, 'event');
  assert.equal(of.fresh.axis, 'genre');
  assert.equal(of.quick.axis, 'genre');
  assert.equal(of.m.axis, 'mood');
  assert.equal(of.e.axis, 'era');
  assert.equal(of.gm.axis, 'genre', 'a genre in the name is never overruled by its tags');
});

test('there is one copy of the rules: neither side defines its own', () => {
  const sources = ['axes.mjs', 'web/app/classify.js',
    ...readdirSync('web/app').map(f => `web/app/${f}`), ...readdirSync('web/screens').map(f => `web/screens/${f}`)];
  for (const f of new Set(sources)) {
    const src = readFileSync(f, 'utf8');
    assert.doesNotMatch(src, /^const (INBOX|EVENT|DJSET|ERA|OCCASION|MOOD)\s*=/m, f);
    assert.doesNotMatch(src, /^function (genreInName|addedShape|facetAxis)\b/m, f);
  }
});

/* ---- each difference the two copies used to have, now settled the page's way ---- */

const axis = (name, opts) => nodeClassify({ playlists: [pl('x', name, opts)] }).x;

test('B10: "bloc party" and "e1" are not event words (they were in the CLI only)', () => {
  // "Bloc Party" is a band; "party" makes it an occasion by the shared rule,
  // not an event. "E1" on its own is a postcode, not a club.
  assert.equal(axis('Bloc Party').axis, 'context');
  assert.notEqual(axis('E1 London').axis, 'event');
  assert.equal(NAME_RULES.EVENT.test('E1 London'), false);
});

test('B10: "our … mix" is not a DJ set (it was in the CLI only)', () => {
  assert.equal(axis('Our Summer Mix').axis, 'genre');
  assert.equal(axis('Our Summer Mix').target, false);
  assert.equal(NAME_RULES.DJSET.test('Our mix'), false);
});

test('B10: one library\'s playlist words are not mood words (they were in the CLI only)', () => {
  for (const n of ['Headache', 'Forbidden', 'On Road', 'Danceable', 'Graveyard Shift', 'Killstreak'])
    assert.equal(NAME_RULES.MOOD.test(n), false, n);
  assert.equal(axis('Headache').axis, 'genre');
  assert.equal(axis('Headache').target, false, 'and no genre named, so nothing is filed into it');
});

test('B10: a genre in the name beats a mood word (the CLI had no genreInName)', () => {
  assert.equal(axis('Happy Hardcore').axis, 'genre');
  assert.equal(axis('Happy Hardcore').target, true);
  assert.equal(axis('Happy Hardcore').why, '“happy hardcore” in the name');
  assert.equal(genreInName('D&B Rollers', new Set(genreWords())), 'drum and bass rollers');
});

test('B10: a playlist that names no genre is not a filing target (the CLI made every one a target)', () => {
  for (const n of ['Sunday', 'Bangers', 'Car', 'Favourites']) {
    assert.equal(axis(n).axis, 'genre', n);
    assert.equal(axis(n).target, false, n);
  }
});

test('B10: mood playlists take no suggestions by default (the CLI made them targets)', () => {
  assert.equal(axis('mellow emma').axis, 'mood');
  assert.equal(axis('mellow emma').target, false);
});

test('B10: built in one sitting and left alone is an event (the CLI had no date rule)', () => {
  assert.equal(axis('with Sam and Jo', { n: 30, span: 0.3, since: 100 }).axis, 'event');
  assert.equal(axis('with Sam and Jo', { n: 30, span: 0.3, since: 3 }).axis, 'genre');
});

test('B10: tags never overrule a genre named in the name (the CLI asked the tags first)', () => {
  const tags = {};
  const tagged = (id, name, n, vocab) => {
    const tracks = [];
    for (let k = 0; k < n; k++) {
      const a = `${id}-a${k}`;
      tags[a] = { tags: vocab.map(t => [t, 100]) };
      tracks.push({ id: `${id}-t${k}`, artists: [{ id: a, name: a }],
                    added_at: new Date(NOW - 3 * day - k * 30 * day).toISOString() });
    }
    return { id, name, tracks };
  };
  const moody = ['chill', 'mellow', 'dreamy', 'downtempo'];
  const lib = { playlists: [
    tagged('h', 'House', 12, moody), tagged('u', 'untitled', 12, moody),
    tagged('g1', 'first thing', 14, ['techno', 'industrial techno', 'hard techno']),
    tagged('g2', 'second thing', 14, ['jungle', 'breakbeat', 'hardcore']),
    tagged('g3', 'third thing', 14, ['techno', 'industrial techno', 'hard techno']),
  ] };
  const cfg = nodeClassify(lib, tags);
  assert.equal(cfg.h.axis, 'genre');
  assert.equal(cfg.u.axis, 'mood', 'with nothing in the name, the same kind of tracks are read as mood');
});

/* ---- what only the CLI has: its hand overrides and the previous config ---- */

test('axes.mjs: an override wins, and a forced axis takes suggestions the way the page\'s picker does', () => {
  const lib = { playlists: [pl('a', 'Lyricism Emma'), pl('b', 'VibinWEmma'), pl('c', 'Bangers'), pl('d', 'Tiny', { n: 3 })] };
  const cfg = axesConfig(lib, { now: NOW, prev: { playlists: {} },
    overrides: { 'Lyricism Emma': 'context', VibinWEmma: 'mood', Bangers: 'genre', Tiny: 'genre' } });
  assert.deepEqual([cfg.a.axis, cfg.a.target], ['context', false]);
  assert.deepEqual([cfg.b.axis, cfg.b.target], ['mood', false]);
  assert.deepEqual([cfg.c.axis, cfg.c.target, cfg.c.why], ['genre', true, 'set by you']);
  assert.equal(cfg.d.target, false, 'never a target below the size gate, whatever the override says');
});

test('axes.mjs: a previous hand edit is kept', () => {
  const lib = { playlists: [pl('a', 'Bangers'), pl('b', 'Jungle')] };
  const prev = { playlists: { a: { axis: 'mood', target: true }, b: { axis: 'genre', target: false } } };
  const cfg = axesConfig(lib, { now: NOW, prev, overrides: {} });
  assert.deepEqual([cfg.a.axis, cfg.a.target], ['mood', true]);
  assert.deepEqual([cfg.b.axis, cfg.b.target], ['genre', false]);
});

test('classifyAxes is pure: no saved corrections, no storage', () => {
  const cfg = classifyAxes({ playlists: [pl('a', 'Jungle')] }, { now: NOW, genreWords: new Set(['jungle']) });
  assert.deepEqual(cfg.a, { name: 'Jungle', axis: 'genre', why: '“jungle” in the name', tracks: 20, target: true });
  assert.equal(classifyAxes({ playlists: [pl('a', 'Jungle')] }, { now: NOW }).a.target, false,
    'with no vocabulary, no genre is ever named');
});
