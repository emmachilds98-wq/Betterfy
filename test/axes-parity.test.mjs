// The page's classify() and the Node CLI axes.mjs used to be two copies of the
// same rules that claimed to mirror each other and had drifted: the CLI had
// its own EVENT/DJSET/MOOD regexes, no genreInName(), no "built in one sitting"
// event rule, no tag gate, and made mood playlists targets
// (docs/BUILD-5-PLAN.md B10). Both now run core/playlists/axes.mjs. These tests
// hold them together: the page as built (docs/index.html, the way every web
// test reads it) against axes.mjs as imported, over a broad set of names.

const BUNDLE = readFileSync(new URL('../docs/index.html', import.meta.url), 'utf8');
const NOW = Date.parse('2026-09-06T00:00:00Z');
const day = 86400000;

/** The page's classify(), evaluated from the built page. */
function pageClassify(saved = {}) {
  const i = BUNDLE.indexOf('/* ---------- axis classification');
  const j = BUNDLE.indexOf('/* ---------- reports (mirrors');
  assert.ok(i > 0 && j > i, 'classify block not found — rebuild with npm run build:web');
  const p = BUNDLE.indexOf('/* Generated by bundler.mjs');
  const pEnd = BUNDLE.indexOf('/* ============', p);
  assert.ok(p > 0 && pEnd > p, 'core bundle not found — rebuild with npm run build:web');
  const sandbox = { LS: { getItem: k => (k === 'bf_axes' ? JSON.stringify(saved) : null) }, console };
  vm.createContext(sandbox);
  vm.runInContext(BUNDLE.slice(p, pEnd), sandbox);
  vm.runInContext(`const ALL_SONGS_NAME = 'All Songs — Betterfy';`, sandbox);
  const m = BUNDLE.indexOf("const ALL_SONGS_KEY = 'bf_allsongs';");
  const mEnd = BUNDLE.indexOf('/** A row of tag chips', m);
  assert.ok(m > 0 && mEnd > m, 'mirror predicate not found — rebuild with npm run build:web');
  vm.runInContext(BUNDLE.slice(m, mEnd), sandbox);
  vm.runInContext(BUNDLE.slice(i, j), sandbox);
  const classify = vm.runInContext('classify', sandbox);
  // Out of the vm's realm, so deepEqual compares values rather than prototypes.
  return (lib, tags = null) => JSON.parse(JSON.stringify(classify(lib, tags, NOW)));
}

/** The CLI's first pass: no hand overrides, no previous config. */
const nodeClassify = (lib, tags = null) =>
  JSON.parse(JSON.stringify(axesConfig(lib, { tags, now: NOW, overrides: {}, prev: { playlists: {} } })));

/** A playlist of `n` tracks, added over `span` days, ending `since` days ago. */
const pl = (id, name, { n = 20, span = 900, since = 2 } = {}) => ({
  id, name,
  tracks: Array.from({ length: n }, (_, k) => ({
    id: id + '-' + k,
    added_at: new Date(NOW - since * day - (span * day * (n - 1 - k)) / Math.max(1, n - 1)).toISOString(),
  })),
});

