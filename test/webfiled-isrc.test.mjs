import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';

/*
 * Build 5, B4 and B5 (docs/BUILD-5-PLAN.md §1.3), run out of the built page.
 *
 * B4: a liked track was "filed" only if that exact Spotify id sat in a
 * playlist. Like the single and file the album copy, and the single stayed in
 * the File queue forever, though the recording is filed. Same ISRC, or the same
 * trackKey (artist, title, version), now counts as filed.
 *
 * B5: rejecting a pick re-ranked the card with bare rank(), so a card whose
 * picks came from the artist's filing history lost that fallback, and every
 * re-ranked pick lost its `via`. Both paths now go through backlogSuggest().
 */

const BUNDLE = readFileSync(new URL('../docs/index.html', import.meta.url), 'utf8');
const own = x => JSON.parse(JSON.stringify(x));

function slice(from, to, what) {
  const i = BUNDLE.indexOf(from), j = BUNDLE.indexOf(to, i);
  assert.ok(i > 0 && j > i, `${what} not found — rebuild with npm run build:web`);
  return BUNDLE.slice(i, j);
}

/** The reports section with the scoring core it is bundled alongside. */
function page(feedback = {}) {
  const sandbox = { console, FB: feedback, LS: { getItem: () => null, setItem: () => {} } };
  vm.createContext(sandbox);
  vm.runInContext(slice('/* Generated by bundler.mjs', '/* ---------- storage ----------', 'scoring core'), sandbox);
  vm.runInContext('const mmss = ms => ms == null ? "—" : Math.floor(ms/60000) + ":" + String(Math.round(ms%60000/1000)).padStart(2,"0");', sandbox);
  vm.runInContext(slice('/* ---------- reports (mirrors', '/* ===================== UI', 'reports'), sandbox);
  vm.runInContext('const ALL_SONGS_NAME = "All Songs — Betterfy";', sandbox);
  return sandbox;
}

const track = (id, artist, title, over = {}) => ({
  id, name: title, artists: [{ id: 'a-' + artist, name: artist }],
  album: 'Album ' + id, duration_ms: 200000, isrc: 'ISRC' + id, popularity: 50,
  added_at: '2024-01-01T00:00:00Z', ...over });

const TAGS = {
  'a-Tim Reaper': { tags: [['jungle', 100], ['breakbeat', 80]] },
  'a-Dwarde':     { tags: [['jungle', 100], ['hardcore', 60]] },
  'a-Blawan':     { tags: [['techno', 100]] },
  'a-Surgeon':    { tags: [['techno', 100], ['industrial techno', 70]] },
};

function library() {
  const playlists = [
    { id: 'p1', name: 'Jungle', tracks: [track('t1', 'Tim Reaper', 'Rinse It'), track('t2', 'Dwarde', 'Dread')] },
    { id: 'p2', name: 'Techno', tracks: [track('t3', 'Blawan', 'Why They Hide'), track('t4', 'Surgeon', 'Badger Bite')] },
  ];
  const cfg = { p1: { name: 'Jungle', axis: 'genre', target: true }, p2: { name: 'Techno', axis: 'genre', target: true } };
  return { lib: { user: { id: 'u' }, playlists, liked: [track('t5', 'Blawan', 'Getting Me Down')] }, cfg };
}

const backlogIds = (lib, cfg, fb) => own(page(fb).buildReports(lib, cfg, TAGS).backlog.map(b => b.id));

/* ---- B4 ---- */

test('a liked release whose ISRC is already filed under another release is filed, not in the queue', () => {
  const { lib, cfg } = library();
  assert.deepEqual(backlogIds(lib, cfg), ['t5'], 'the fixture has one unfiled liked track');
  // The single: a different Spotify id and a different title spelling, but the
  // same recording (ISRC) as the album track filed in Jungle.
  lib.liked.push(track('s1', 'Tim Reaper', 'Rinse It (Single)', { isrc: 'ISRCt1', album: 'Rinse It — Single' }));
  assert.deepEqual(backlogIds(lib, cfg), ['t5'], 'same ISRC as a filed track: already filed');
});

test('a liked release with the same trackKey as a filed track is filed, even with no ISRC', () => {
  const { lib, cfg } = library();
  // A remaster, no ISRC: the same artist, title and (no) version as t3.
  lib.liked.push(track('r1', 'Blawan', 'Why They Hide - 2020 Remaster', { isrc: undefined }));
  assert.deepEqual(backlogIds(lib, cfg), ['t5']);
});

test('a different version of a filed track is still unfiled: remixes are different records', () => {
  const { lib, cfg } = library();
  lib.liked.push(track('x1', 'Blawan', 'Why They Hide (Surgeon Remix)'));
  assert.deepEqual(backlogIds(lib, cfg).sort(), ['t5', 'x1']);
});

test('a copy that is only in the mirror playlist does not count as filed', () => {
  const { lib, cfg } = library();
  const single = track('s1', 'Nobody', 'Lonely', { isrc: 'ISRC-LONELY' });
  lib.liked.push(single);
  lib.playlists.push({ id: 'as1', name: 'All Songs — Betterfy', tracks: [track('s2', 'Nobody', 'Lonely', { isrc: 'ISRC-LONELY' })] });
  cfg.as1 = { name: 'All Songs — Betterfy', axis: 'context', target: false };
  assert.deepEqual(backlogIds(lib, cfg).sort(), ['s1', 't5']);
});

test('tracks with no title or ISRC never match each other by an empty key', () => {
  const { lib, cfg } = library();
  lib.playlists[0].tracks.push({ id: 'stub1' });
  lib.liked.push({ id: 'stub2', artists: [] });
  assert.deepEqual(backlogIds(lib, cfg).sort(), ['stub2', 't5']);
});

/* ---- B5 ---- */

test('backlogSuggest is what buildReports fills every card with', () => {
  const { lib, cfg } = library();
  const s = page();
  const r = s.buildReports(lib, cfg, TAGS);
  const gated = vm.runInContext('(tags) => gateTags(tags, tagGate(tags))', s)(TAGS);
  const again = s.backlogSuggest(lib.liked[0], lib, cfg, gated, r.profiles, r.idf);
  assert.deepEqual(own(again), own(r.backlog[0].suggest));
  assert.equal(r.backlog[0].suggest[0].via, 'tags');
});

test('re-ranking after a reject keeps the filing-history fallback and its via label', () => {
  const { lib, cfg } = library();
  // An artist with no tags at all, whose other tracks are filed in Jungle (2)
  // and Techno (1): history points at Jungle.
  lib.playlists[0].tracks.push(track('h1', 'Nobody', 'One'), track('h2', 'Nobody', 'Two'), track('h3', 'Nobody', 'Three'));
  lib.liked.push(track('n1', 'Nobody', 'New One'));
  const fb = {};
  const s = page(fb);
  const r = s.buildReports(lib, cfg, TAGS);
  const row = own(r.backlog).find(b => b.id === 'n1');
  assert.equal(row.suggest[0].via, 'history');
  assert.equal(row.suggest[0].id, 'p1');

  // What the reject handler does: record, then re-rank through backlogSuggest.
  const gated = vm.runInContext('(tags) => gateTags(tags, tagGate(tags))', s)(TAGS);
  const raw = lib.liked.find(t => t.id === 'n1');
  const before = own(s.backlogSuggest(raw, lib, cfg, gated, r.profiles, r.idf));
  assert.deepEqual(before, row.suggest, 'unchanged with nothing rejected');
  fb.n1 = { skips: 0, lastSkip: null, rejected: ['p2'] };   // a pick it did not even show
  const after = own(s.backlogSuggest(raw, lib, cfg, gated, r.profiles, r.idf));
  assert.equal(after[0]?.via, 'history', 'bare rank() dropped this: a tagless artist got no pick at all');
  assert.equal(after[0]?.id, 'p1');
  fb.n1.rejected.push('p1');
  assert.deepEqual(own(s.backlogSuggest(raw, lib, cfg, gated, r.profiles, r.idf)), [], 'a rejected history pick is gone too');
});

test('the reject handler re-ranks through backlogSuggest, not bare rank()', () => {
  const body = slice('async reject(ctx, el, e) {', 'rebuildReports(); render();', 'reject handler');
  assert.match(body, /t\.suggest = raw \? backlogSuggest\(raw, LIB, CFG, gateTags\(TAGS, tagGate\(TAGS\)\), R\.profiles, R\.idf\) : \[\]/);
  assert.doesNotMatch(body, /rank\(raw/);
});

test('a liked song whose only playlist is an inflow (Shazam, To sort) is still waiting to be filed', () => {
  const { lib, cfg } = library();
  const shazamed = track('z1', 'Dwarde', 'Bassline Pressure');
  lib.liked.push(shazamed);
  lib.playlists.push({ id: 'in1', name: 'My Shazam Tracks', tracks: [shazamed, track('t3', 'Blawan', 'Why They Hide')] });
  cfg.in1 = { name: 'My Shazam Tracks', axis: 'inbox', target: false };
  assert.deepEqual(backlogIds(lib, cfg).sort(), ['t5', 'z1'], 'only in an inbox playlist: unfiled');
  // A mood or context playlist is a real place it was put, so it still counts.
  cfg.in1.axis = 'context';
  assert.deepEqual(backlogIds(lib, cfg), ['t5']);
});
