// Writes scripts/ui-shots/gallery/c3.html: WP-C3's "new genre?" names and
// Discover's "sounds like" card, drawn by the real code in the built page on
// fixture CLAP embeddings, for gallery.cjs to screenshot.
//   node build-web.mjs && node scripts/ui-shots/c3-gallery.mjs && node scripts/ui-shots/gallery.cjs --only=c3
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import { table, clapField, resetSeed } from '../../test/fixtures/clap-fixture.mjs';

const read = f => readFileSync(new URL(`../../docs/${f}`, import.meta.url), 'utf8');
const PAGE = read('index.html');
const slice = (from, to) => { const i = PAGE.indexOf(from), j = PAGE.indexOf(to, i);
  if (i < 0 || j < i) throw new Error(`${from} not found: rebuild first`); return PAGE.slice(i, j); };
const esc = x => String(x ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

resetSeed();
const lean = [['Night Drift', 'Kordhell-ish', { phonk: 1 }], ['Cowbell Run', 'Memphis Unit', { phonk: 1 }],
  ['Pressure', 'Dense Fog', { dnb: 0.6, rolling: 0.8 }], ['Low End Club', 'K-Mira', { bass: 1 }],
  ['Jump Up Jersey', 'Club Kidz', { jersey: 1 }], ['Rinse', 'Roller Unit', { dnb: 1 }]];
const tracks = [], records = [];
for (let n = 0; n < 24; n++) {
  const [name, artist, mix] = lean[n % lean.length];
  const id = `t${n}`;
  tracks.push({ id, name: n < lean.length ? name : `${name} ${Math.floor(n / lean.length) + 1}`, artists: [{ name: artist }] });
  records.push({ v: 1, id, at: 1, clap: clapField(mix) });
}
const s = { esc, Set, Map, Promise, console, atob, btoa, R: { clusters: [] }, LIB: { liked: tracks, playlists: [] },
  AUDIO: { records: new Map(records.map(r => [r.id, r])) }, audioModelUrl: f => f,
  idb: { get: async () => null, set: async () => {} }, syncStamped: async () => false,
  fetch: async () => ({ ok: true, json: async () => table() }), fire: p => p, render: () => {} };
vm.createContext(s);
vm.runInContext(read('audio.js'), s);
vm.runInContext(slice('function emptyState(', 'function secMisfile()'), s);
vm.runInContext(slice('/* ======================= gaps: docs/SMARTER-GENRES-PLAN.md, phase 3', '/* ---------- shuffle: spacing'), s);
vm.runInContext(slice('/* ---------- CLAP: names for "new genre?" groups', '/** Redraw only the panel'), s);
const run = (code, ...a) => vm.runInContext(code, s)(...a);

const samples = [{ title: 'Night Drift', artist: 'Kordhell-ish' }, { title: 'Cowbell Run', artist: 'Memphis Unit' }];
const base = { kind: 'new', size: 9, nearest: { name: 'Hard House' }, artists: ['Kordhell-ish', 'Memphis Unit'], samples };
const cards = [
  { ...base, i: 0, suggest: { name: 'phonk', alts: [{ name: 'jersey club' }], sounds: 'dark rolling bassline' } },
  { ...base, i: 1, confirmed: 'Drift phonk' },
  { ...base, i: 2 },
].map(c => run('proposalCard', c)).join('');

await vm.runInContext('clapTable()', s);
const before = vm.runInContext('soundSearchHTML()', s);
await vm.runInContext('clapSearch("phonk")', s);
const found = vm.runInContext('soundSearchHTML()', s);
await vm.runInContext('clapSearch("bass")', s);
const near = vm.runInContext('soundSearchHTML()', s);

writeFileSync(new URL('./gallery/c3.html', import.meta.url), `<!-- Generated by c3-gallery.mjs — do not edit here. -->
<h2>New genre? named by sound: suggested, confirmed, unnamed</h2>
<div class="rows">${cards}</div>
<h2>Discover: sounds like, before a search</h2>${before}
<h2>Discover: sounds like “phonk”</h2>${found}
<h2>Discover: not a phrase in the list</h2>${near}
`);
console.log('wrote scripts/ui-shots/gallery/c3.html');
