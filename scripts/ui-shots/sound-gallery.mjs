const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const row = (name, html) => `<div class="gal-row"><code>${esc(name)}</code><div>${html}</div></div>`;
const section = (title, rows) => `<section class="gal-sec"><h3>${esc(title)}</h3>${rows.join('')}</section>`;

/** The gallery fragment: every renderer on every fixture, labelled. */
export function galleryHtml() {
  const F = FIXTURES;
  return [
    '<!-- Generated by scripts/ui-shots/sound-gallery.mjs from its FIXTURES. Do not edit by hand. -->',
    '<style>.gal-sec{padding:16px 20px;border-bottom:1px solid var(--line)}.gal-sec h3{margin:0 0 10px;font:600 15px var(--display);color:var(--ink)}',
    '.gal-row{display:grid;grid-template-columns:150px minmax(0,1fr);gap:12px;align-items:center;padding:6px 0}.gal-row code{font:12px var(--mono);color:var(--ink-3)}',
    '.gal-art{width:220px;max-width:100%}.gal-art .tile{aspect-ratio:1;border-radius:var(--r-2);background:var(--surface-3)}',
    '.gal-card{max-width:420px;padding:16px;border:1px solid var(--line);border-radius:var(--r-3);background:var(--surface)}',
    '@media (max-width:600px){.gal-row{grid-template-columns:1fr;gap:4px}}</style>',
    section('soundChip', Object.entries(F.sound).map(([k, v]) => row(k, S.soundChip(v) || '<i>(nothing)</i>'))),
    section('sectionStrip', Object.entries(F.sound).filter(([, v]) => v.sections)
      .map(([k, v]) => row(k, `<div class="gal-art"><div class="tile"></div>${S.sectionStrip(v)}</div>`))),
    section('evidenceBadges', Object.entries(F.evidence).map(([k, v]) => row(k, S.evidenceBadges(v)))),
    section('bandChip', F.band.map(([b, p]) => row(p == null ? b : `${b}, ${p}`, S.bandChip(b, p)))),
    section('profileRow', Object.entries(F.profile).map(([k, v]) => row(k, S.profileRow(v)))),
    section('listenPill', Object.entries(F.listen).map(([k, v]) => row(k, S.listenPill(v) || '<i>(nothing: off)</i>'))),
    section('listenCard + missedList', Object.entries(F.listen).map(([k, v]) =>
      row(k, `<div class="gal-card">${S.listenCard(v)}${S.missedList(v) ? `<div style="margin-top:14px">${S.missedList(v)}</div>` : ''}</div>`))),
  ].join('\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dir = new URL('./gallery/', import.meta.url);
  mkdirSync(dir, { recursive: true });
  writeFileSync(new URL('sound.html', dir), galleryHtml());
  console.log('wrote scripts/ui-shots/gallery/sound.html');
}
