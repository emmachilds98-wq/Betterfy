// Writes scripts/ui-shots/gallery/ui6.html: UI-6's cards drawn by the real
// renderers in the built page, on fixtures, for gallery.cjs to screenshot.
//   node build-web.mjs && node scripts/ui-shots/ui6-gallery.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const PAGE = readFileSync(new URL('../../docs/index.html', import.meta.url), 'utf8');
const slice = (from, to) => { const i = PAGE.indexOf(from), j = PAGE.indexOf(to, i);
  if (i < 0 || j < i) throw new Error(`${from} not found: rebuild first`); return PAGE.slice(i, j); };
const esc = x => String(x ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const s = { esc, Set, Map, R: { clusters: [] }, fire: () => {}, render: () => {}, BetterfyGaps: { MIN_GAP: 12 } };
vm.createContext(s);
vm.runInContext(slice('function emptyState(', 'function secMisfile()'), s);
vm.runInContext(slice('/* ======================= gaps: docs/SMARTER-GENRES-PLAN.md, phase 3', '/* ---------- shuffle: spacing'), s);
vm.runInContext(slice('function pairBars(', '/** Whether long engine work'), s);
const run = (code, ...a) => vm.runInContext(code, s)(...a);

const between = [{ id: 'a', name: 'Bassline' }, { id: 'b', name: 'Dubstep' }];
const samples = [{ title: 'Wobble Theory', artist: 'Northside Unit' }, { title: 'Low End Club', artist: 'K-Mira' },
  { title: 'Night Bus 88', artist: 'Halfstep' }, { title: 'Pressure', artist: 'Dense Fog' }];
const cards = [
  { kind: 'hybrid', i: 0, name: 'Bassline / Dubstep', size: 14, played: 3, mixed: 4, between,
    artists: ['Northside Unit', 'K-Mira', 'Halfstep'], samples },
  { kind: 'new', i: 0, size: 9, nearest: { name: 'Hard House' }, artists: ['Donk Lads', 'Bouncy B'], samples: samples.slice(0, 3) },
  { kind: 'pick', i: 0, size: 6, between: [{ id: 'c', name: 'Drum & Bass' }, { id: 'd', name: 'Jungle' }], artists: ['Rollers Inc'] },
  { kind: 'pick', i: 1, size: 6, between: [{ id: 'c', name: 'Drum & Bass' }, { id: 'd', name: 'Jungle' }], artists: ['Rollers Inc'], filedTo: ['Jungle'] },
].map(c => run('proposalCard', c)).join('');

const p = x => x == null ? '—' : Math.round(x * 100) + '%';
const v = (nfWith, gate) => ({ mine: { top1: 0.58, scored: 412, neverFiled: { scored: 64, top1: 0.31 },
  withAudio: { top1: 0.6, heard: 290, heardNeverFiled: 41, changed: 23, neverFiled: { top1: nfWith }, gate } } });
const pass = run('audioCard', v(0.39, { pass: true, bar: { minLift: 0.05 },
  text: '+8 points on tracks by artists you hadn\'t filed in a genre playlist yet, and +2 points overall.' }), p);
const fail = run('audioCard', v(0.33, { pass: false, bar: { minLift: 0.05 },
  text: 'Not enough lift on never-filed artists (+2 points; the bar is +5 points), so it stays display-only.' }), p);

const seg = ['Sure', 'Likely', 'Unsure'].map((w, i) => `<button type="button" aria-pressed="${i === 0}"><span class="band band-${w.toLowerCase()}">${w}</span> <span class="n">${[12, 31, 7][i]}</span></button>`).join('');

writeFileSync(new URL('./gallery/ui6.html', import.meta.url), `<!-- UI-6 (Tidy, New playlists, Engine) on fixtures.
     Generated by scripts/ui-shots/ui6-gallery.mjs from the built page: do not edit by hand. -->
<h2>Tidy: how sure</h2>
<div class="seg mfbands" role="group">${seg}</div>
<h2>Empty states</h2>
${run('emptyState', 'Everything fits where it is', 'No track sits in a playlist that fits far worse than another one on the same axis. New ones show up here after a sync.')}
<div style="height:12px"></div>
${run('emptyState', 'Nothing Sure', 'Nothing is clearly in the wrong place. Likely has the more speculative ones.', { compact: true })}
<h2>New playlists: proposals by sound</h2>
<div class="rows">${cards}</div>
<h2>Engine: adding how it sounds, passed</h2>
<div class="card">${pass}</div>
<h2>Engine: not passed</h2>
<div class="card">${fail}</div>
`);
console.log('wrote gallery/ui6.html');
